export type Lang = 'en' | 'zh' | 'ja' | 'ko' | 'es' | 'de';

export const SUPPORTED_LANGS: ReadonlyArray<{ code: Lang; label: string }> = [
  { code: 'en', label: 'English' },
  { code: 'zh', label: '简体中文' },
  { code: 'ja', label: '日本語' },
  { code: 'ko', label: '한국어' },
  { code: 'es', label: 'Español' },
  { code: 'de', label: 'Deutsch' },
];

export function isValidLang(v: string | null | undefined): v is Lang {
  return v === 'en' || v === 'zh' || v === 'ja' || v === 'ko' || v === 'es' || v === 'de';
}

export function detectInitialLang(queryLang?: string | null): Lang {
  if (isValidLang(queryLang)) return queryLang;
  if (typeof window !== 'undefined') {
    const saved = window.localStorage.getItem('caliper-lang');
    if (isValidLang(saved)) return saved;
    const nav = (window.navigator?.language || '').toLowerCase();
    if (nav.startsWith('zh')) return 'zh';
    if (nav.startsWith('ja')) return 'ja';
    if (nav.startsWith('ko')) return 'ko';
    if (nav.startsWith('es')) return 'es';
    if (nav.startsWith('de')) return 'de';
  }
  return 'en';
}

